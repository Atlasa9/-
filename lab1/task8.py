# Даны три точки A, B, C на числовой оси. Точка C расположена между точками A и B. Найти произведение длин отрезков AC и BC

a, b, c = map(float, input("Введите координаты трех точек (a b c): ").split())

ac = abs(c - a)
bc = abs(c - b)

print(f"Длина отрезка AC: {ac}")
print(f"Длина отрезка BC: {bc}")
print(f"Произведение отрезков AC и BC: {ac * bc}")