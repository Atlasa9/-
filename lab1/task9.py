# Даны координаты двух противоположных вершин прямоугольника: (x1, y1), (x2, y2).
# Стороны прямоугольника параллельны осям координат. Найти периметр и площадь данного прямоугольника.

x1, y1, x2, y2 = map(float, input("Введите координаты двух точек (x1 y1 x2 y2): ").split())

width = abs(x2 - x1)
height = abs(y2 - y1)

S = width * height
P = 2 * (width + height)

print(f"Площадь прямоугольника (S) = {S}")
print(f"Периметр прямоугольника (P) = {P}")