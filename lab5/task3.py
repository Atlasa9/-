# Даны целые числа N (> 2), A и B.
# Сформировать и вывести целочисленный массив размера N, первый элемент которого равен A, второй равен B,а каждый последующий элемент равен сумме всех предыдущих

n = int(input("Введите целое число N (> 2): "))
a = int(input("Введите первый элемент A: "))
b = int(input("Введите второй элемент B: "))

if n <= 2:
    print("N должно быть больше 2.")
else:
    array = [a, b]
    total = a + b

    for _ in range(n - 2):
        array.append(total)
        total += array[-1]

    print("Массив:", array)