# Дано вещественное число A и целое число N (> 0). Используя один цикл, найти значение выражения 1 − A + A^2 − A^3 + . . . ± A^N. 
# Условный оператор не использовать.

a = float(input("Введите вещественное число A: "))
n = int(input("Введите целое число N (> 0): "))

result = 1.0
power = 1.0
sign = -1

for i in range(n):
    power *= a
    result += sign * power
    sign *= -1

print(f"Результат: {result}")