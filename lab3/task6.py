# Даны целые положительные числа A и B (A < B).
# Вывести все целые числа от A до B включительно; при этом каждое число должно выводиться столько раз, каково его значение (например, число 3 выводится 3 раза).

a = int(input("Введите число A: "))
b = int(input("Введите число B (A < B): "))

for number in range(a, b + 1):
    for _ in range(number):
        print(number)