# Дано целое число. Вывести его строку-описание вида «отрицательное четное число», «нулевое число», «положительное нечетное число» и т.д.

n = int(input("Введите целое число: "))

if n == 0:
    print("Нулевое число")
else:
    sign = "Положительное" if n > 0 else "Отрицательное"
    parity = "четное" if n % 2 == 0 else "нечетное"
    print(f"{sign} {parity} число")