# Дано целое число в диапазоне 100–999. Вывести строку-описание данного числа, например: 256 — «двести пятьдесят шесть», 814 — «восемьсот четырнадцать».

ONES = ["", "один", "два", "три", "четыре", "пять",
        "шесть", "семь", "восемь", "девять"]

TEENS = ["десять", "одиннадцать", "двенадцать", "тринадцать", "четырнадцать",
         "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"]

TENS = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят",
        "шестьдесят", "семьдесят", "восемьдесят", "девяносто"]

HUNDREDS = ["", "сто", "двести", "триста", "четыреста", "пятьсот",
            "шестьсот", "семьсот", "восемьсот", "девятьсот"]

number = int(input("Введите число от 100 до 999: "))

if not (100 <= number <= 999):
    print("Число должно быть в диапазоне от 100 до 999")
else:
    words = [HUNDREDS[number // 100]]
    remainder = number % 100

    if 10 <= remainder < 20:
        words.append(TEENS[remainder - 10])
    else:
        words.append(TENS[remainder // 10])
        words.append(ONES[remainder % 10])

    print(" ".join(word for word in words if word))