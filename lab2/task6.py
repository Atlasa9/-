# Дано целое число, лежащее в диапазоне 1–999. Вывести его строку описание вида «четное двузначное число», «нечетное трехзначное число» и т.д.

n = int(input("Введите число от 1 до 999: "))

if n < 1 or n > 999:
    print("Число вне диапазона 1–999")
else:
    parity = "Четное" if n % 2 == 0 else "Нечетное"
    digits = "однозначное" if n < 10 else "двузначное" if n < 100 else "трехзначное"
    print(f"{parity} {digits} число")