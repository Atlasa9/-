# В восточном календаре принят 60-летний цикл, состоящий из 12- летних подциклов, обозначаемых названиями цвета: зеленый, красный, желтый, белый и черный.
# В каждом подцикле годы носят названия животных: крысы, коровы, тигра, зайца, дракона, змеи, лошади, овцы, обезьяны, курицы, собаки и свиньи.
# По номеру года определить его название, если 1984 год — начало цикла: «год зеленой крысы».

animals = [
    "крысы", "коровы", "тигра", "зайца", "дракона", "змеи",
    "лошади", "овцы", "обезьяны", "курицы", "собаки", "свиньи"
]
colors_f = ["зеленой", "красной", "желтой", "белой", "черной"]
colors_m = ["зеленого", "красного", "желтого", "белого", "черного"]
is_masculine = [False, False, True, True, True, False, False, False, False, False, False, False]

year = int(input("Введите год: "))
offset = (year - 1984) % 60
index = offset % 12
color = colors_m[offset // 12] if is_masculine[index] else colors_f[offset // 12]

print(f"год {color} {animals[index]}")